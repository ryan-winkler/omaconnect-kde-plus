const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname,'../Appearance.js'),'utf8').replace(/^\.pragma library\s*/, '');
const api = vm.createContext({}); vm.runInContext(source, api);
function plain(value) { return JSON.parse(JSON.stringify(value)); }
assert.equal(api.normalizeLegacy(undefined).value,'phone');
assert.equal(api.normalizeLegacy(false).value,'phone');
assert.equal(api.normalizeLegacy(true).mode,'automatic');
const state = {bar_icon:{mode:'automatic'}, devices:{'kdeconnect:stable':{alias:'Travel',icon:{mode:'preset',value:'laptop'}}}};
assert.equal(api.barIcon(state,'stable','phone').value,'laptop');
assert.equal(api.deviceIcon(state,'other','unknown').value,'phone');
assert.equal(api.deviceIcon(state,'other','tablet').value,'tablet-symbolic');
assert.equal(api.deviceIcon(state,'other','tv').value,'video-display-symbolic');
assert.equal(api.displayName(state,'stable','New advertised name'),'Travel');
assert.equal(api.displayName(state,'other','<b>Phone</b>'),'<b>Phone</b>');
state.bar_icon = {mode:'preset',value:'share'};
assert.equal(api.barIcon(state,'stable','phone').value,'share');
assert.equal(api.deviceIcon(state,'stable','phone').value,'laptop');
assert.equal(api.normalizeIcon({mode:'image',value:'https://example.org/icon'}).value,'phone');
assert.equal(api.normalizeIcon({mode:'theme',value:'../bad'}).value,'phone');
assert.equal(api.normalizeIcon({mode:'glyph',value:'\u202e'}).value,'phone');
assert.equal(api.glyphFor({mode:'preset',value:'phone'}).length > 0,true);
for (const value of ['phone','desktop','laptop','link','share']) assert.ok(api.presets.some(entry => entry.value === value));
assert.equal(new Set(api.presets.map(entry => api.glyphFor(entry))).size,api.presets.length);
assert.equal(api.glyphFor({mode:'preset',value:'share'}).codePointAt(0),0xF0497);
assert.equal(api.symbolFont(['Liberation Sans','Symbols Nerd Font'],'Liberation Sans'),'Symbols Nerd Font');
assert.equal(api.symbolFont(['JetBrainsMono Nerd Font','Symbols Nerd Font'],'JetBrainsMono Nerd Font'),'JetBrainsMono Nerd Font');
assert.equal(api.symbolFont(['JetBrainsMono Nerd Font','Symbols Nerd Font'],'Symbols Nerd Font'),'Symbols Nerd Font');
assert.equal(api.symbolFont(['Noto Sans Symbols'],'Noto Sans Symbols'),'');
assert.equal(api.symbolFont(['Unverified Nerd Font'],'Unverified Nerd Font'),'');
assert.equal(api.symbolFont(['Unverified Nerd Font','Symbols Nerd Font'],'Unverified Nerd Font'),'Symbols Nerd Font');
assert.equal(api.symbolFont(['Symbols Nerd Font'],'JetBrainsMono Nerd Font'),'Symbols Nerd Font');
assert.equal(api.symbolFont(['Liberation Sans'],'Liberation Sans'),'');
assert.equal(api.library('laptop',[]).some(x => x.value === 'laptop'),true);
assert.equal(api.normalizeIcon({mode:'theme',value:'fixture-line',tint:true}).tint,true);
assert.equal(api.normalizeIcon({mode:'theme',value:'fixture-line',tint:true}).render,'symbolic');
assert.equal(api.normalizeIcon({mode:'theme',value:'kdeconnect',render:'symbolic'}).tint,undefined);
assert.equal(api.symbolicThemeName('go-next-symbolic-rtl'),true);
assert.equal(api.symbolicThemeName('go-next-symbolic-ltr'),true);
assert.equal(api.symbolicThemeName('kdeconnect'),false);
console.log('Appearance resolver: passed');
